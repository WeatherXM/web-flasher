#!/usr/bin/env node
/**
 * Sync the WS2001 uplink decoder from the firmware repository.
 *
 *   node scripts/sync-ws2001-decoder.mjs [path/to/ws2001-firmware/tools/decoders/ws2001_uplink_decoder.js]
 *
 * Copies the decoder to public/decoders/ (downloadable from the site) and regenerates
 * src/lib/ble/ws2001UplinkDecoder.ts, which the WS2001 page copies to the clipboard.
 * Without an argument it regenerates the TS module from the existing public copy.
 */
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicCopy = path.join(root, 'public', 'decoders', 'ws2001_uplink_decoder.js');
const tsModule = path.join(root, 'src', 'lib', 'ble', 'ws2001UplinkDecoder.ts');

if (process.argv[2]) {
  copyFileSync(path.resolve(process.argv[2]), publicCopy);
  console.log(`Copied ${process.argv[2]} -> ${path.relative(root, publicCopy)}`);
}

const source = readFileSync(publicCopy, 'utf8').replace(/\r\n/g, '\n');
const escaped = source.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
writeFileSync(
  tsModule,
  `// GENERATED by scripts/sync-ws2001-decoder.mjs from public/decoders/ws2001_uplink_decoder.js - do not edit.\n` +
    `// Source of truth: ws2001-firmware/tools/decoders/ws2001_uplink_decoder.js\n` +
    `export const WS2001_UPLINK_DECODER = \`${escaped}\`;\n`,
);
console.log(`Wrote ${path.relative(root, tsModule)}`);
